# Generate scripts\<Name>.txt: startup, CLIENTPUBLICDATA.INI, then every main-window message of the ported handlers
# (main_msgmap.inc) sent directly: NULL, and for each request id / device-data state the handler body compares,
# a REQUEST_USB_DEVICE_DATA or USB_DEVICE_DATA_INFO payload.
#   powershell -File make_main.ps1 [-Value 1] [-Name main1]
# Keep ASCII.
param([int]$Value = 1, [string]$Name = 'main')
$src = 'C:\Users\Administrator\Downloads\NanoImpact_20230510\NanoImpact\source\NanoImpact2020cfe'
$defs = Join-Path $PSScriptRoot '..\..\src\NanoImpact.Core\Generated\Defines.g.cs'
$map = Join-Path $PSScriptRoot 'main_msgmap.inc'
$startup = Get-Content (Join-Path $PSScriptRoot 'scripts\startup.txt') -Encoding UTF8

$val = @{}
foreach ($m in (Select-String -Path $defs -Pattern 'public const int (\w+) = (-?\d+|0x[0-9A-Fa-f]+);')) {
    $v = $m.Matches[0].Groups[2].Value
    $val[$m.Matches[0].Groups[1].Value] = $(if ($v -like '0x*') { [Convert]::ToInt32($v.Substring(2), 16) } else { [int]$v })
}
$cpp = [IO.File]::ReadAllText((Join-Path $src 'NanoImpact2020cfeDlg.cpp'), [Text.Encoding]::UTF8)
$cpp = [regex]::Replace($cpp, '(?s)/\*.*?\*/', '')
function Body([string]$fn) {
    $m = [regex]::Match($cpp, '(?ms)^LRESULT CNanoImpact2020cfeDlg::' + $fn + '\(WPARAM wParam, LPARAM lParam\)\s*\{(.*?)^\}')
    if ($m.Success) { $m.Groups[1].Value } else { '' }
}
function Num([string]$name) { if ($val.ContainsKey($name)) { $val[$name] } elseif ($name -match '^-?\d+$') { [int]$name } else { $null } }

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("# generated by make_main.ps1 -Value $Value (do not edit)")
$startup | Where-Object { $_ -notmatch '^#' } | ForEach-Object { $lines.Add($_) }
$lines.Add('CLIENTINI ini\CLIENTPUBLICDATA.INI')
$lines.Add("AUTOBC $($Value % 2)")
$n = (0..9 | ForEach-Object { $Value + $_ }) -join ','
$d = (0..9 | ForEach-Object { "$($Value + $_).5" }) -join ','
$w = (0..9 | ForEach-Object { $Value * 3 + $_ }) -join ','
$shutdown = New-Object System.Collections.Generic.List[string]
foreach ($e in (Select-String -Path $map -Pattern 'if \(msg == (\w+)\) return g_main\.(\w+)\(')) {
    $msgName = $e.Matches[0].Groups[1].Value; $fn = $e.Matches[0].Groups[2].Value
    $msg = Num $msgName
    if ($msg -eq $null) { continue }
    $body = Body $fn
    $out = New-Object System.Collections.Generic.List[string]
    $out.Add("MAIN $msg 0 NULL")
    if ($body -match 'REQUEST_USB_DEVICE_DATA\*\)lParam') {
        $ids = @([regex]::Matches($body, 'nRequestID\s*==\s*(\w+)') | ForEach-Object { $_.Groups[1].Value } | Select-Object -Unique)
        # values the body compares nRequestOption / nRequestData[0] / public scan state against
        $opts = @([regex]::Matches($body, 'nRequestOption\s*==\s*(\w+)') | ForEach-Object { Num $_.Groups[1].Value } | Where-Object { $_ -ne $null } | Select-Object -Unique)
        $d0s = @([regex]::Matches($body, 'nRequestData\[0\]\s*==\s*(\w+)') | ForEach-Object { Num $_.Groups[1].Value } | Where-Object { $_ -ne $null } | Select-Object -Unique)
        $states = @([regex]::Matches($body, 'm_SemSEScanControlPublicData\.(\w+)\s*==\s*(\w+)') | ForEach-Object { $v = Num $_.Groups[2].Value; if ($v -ne $null) { "$($_.Groups[1].Value) $v" } } | Select-Object -Unique)
        $rest = (1..9 | ForEach-Object { $Value + $_ }) -join ','
        $reqs = New-Object System.Collections.Generic.List[string]
        foreach ($id in $ids) {
            $num = Num $id
            if ($num -eq $null) { continue }
            foreach ($type in 0, 1) { $reqs.Add("$num,$type,$($Value + 2);$n;$d;T$Value") }
            foreach ($o in $opts) { $reqs.Add("$num,0,$o;$n;$d;T$Value") }
            foreach ($v0 in $d0s) { foreach ($o in @($opts + @($Value + 2))) { $reqs.Add("$num,0,$o;$v0,$rest;$d;T$Value") } }
        }
        $reqs | Select-Object -Unique | ForEach-Object { $out.Add("MAIN $msg 0 REQ $_") }
        # branches on earlier public scan state: set the field, then send each request id once more
        foreach ($s in $states) {
            $out.Add("SETF scan $s")
            foreach ($id in $ids) { $num = Num $id; if ($num -ne $null) { $out.Add("MAIN $msg 0 REQ $num,0,$($Value + 2);$n;$d;T$Value") } }
        }
        $out.Add("MAIN $msg 0 REQ 99999,0,0;$n;$d;x")
    }
    elseif ($body -match 'USB_DEVICE_DATA_INFO\*\)lParam') {
        $states = @([regex]::Matches($body, 'UsbDeviceDataInfo\.n(?:State|Command)\s*==\s*(\w+)') | ForEach-Object { Num $_.Groups[1].Value } | Where-Object { $_ -ne $null } | Select-Object -Unique)
        if ($states.Count -eq 0) { $states = @(0, 1, 2, 3) }
        foreach ($s in $states + @(-1, 9)) { $out.Add("MAIN $msg $Value INFO $s,$s;$n;$w;$w;$d;$Value.25;r") }
    }
    elseif ($body -match 'INTEGRATED_COMMAND_STRUCT\*\)lParam') { $out.Add("MAIN $msg $Value INTEG") }
    elseif ($body -notmatch '\*\)lParam') { foreach ($wp in 0, 1, 2) { $out.Add("MAIN $msg $wp INT $Value") } }
    # other struct payloads (SEM_CONTROL_*) are never sent by the device layer: NULL only
    # flow-control messages can shut the system down: run them last
    if ($fn -eq 'OnSetUsbDeviceSEMControlDataToFlowControl') { $out | ForEach-Object { $shutdown.Add($_) } } else { $out | ForEach-Object { $lines.Add($_) } }
}
$shutdown | ForEach-Object { $lines.Add($_) }
$file = Join-Path $PSScriptRoot "scripts\$Name.txt"
[IO.File]::WriteAllLines($file, $lines, (New-Object Text.UTF8Encoding($false)))
"make_main: $($lines.Count) lines -> $file"
