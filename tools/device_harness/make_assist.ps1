# Generate scripts\<Name>.txt: the startup scenario, then every ModularAssistDevice method (out\src\assist_dispatch.inc) once.
# Methods taking REQUEST_USB_DEVICE_DATA* are called once for every REQIDX_* id their body compares against.
#   powershell -File make_assist.ps1 [-Value 1] [-Name assist1]
# Argument values: int = Value, double = Value.5, CString = "Value.25", request n = Value,Value+1,.. d = Value.5,.. sz = "Value".
# Keep ASCII.
param([int]$Value = 1, [string]$Name = 'assist')
$src = 'C:\Users\Administrator\Downloads\NanoImpact_20230510\NanoImpact\source\NanoImpact2020cfe'
$inc = Join-Path $PSScriptRoot 'out\src\assist_dispatch.inc'
$defs = Join-Path $PSScriptRoot '..\..\src\NanoImpact.Core\Generated\Defines.g.cs'
$startup = Get-Content (Join-Path $PSScriptRoot 'scripts\startup.txt') -Encoding UTF8
$keys = Select-String -Path $inc -Pattern '^DISPATCH\("([^"]+)"' | ForEach-Object { $_.Matches[0].Groups[1].Value }

# REQIDX_* values
$reqVal = @{}
foreach ($m in (Select-String -Path $defs -Pattern 'public const int (REQIDX_\w+) = (-?\d+|0x[0-9A-Fa-f]+);')) {
    $v = $m.Matches[0].Groups[2].Value
    $reqVal[$m.Matches[0].Groups[1].Value] = $(if ($v -like '0x*') { [Convert]::ToInt32($v.Substring(2), 16) } else { [int]$v })
}
# REQIDX_* ids compared inside each method of ModularAssistDevice.cpp
$cpp = [IO.File]::ReadAllText((Join-Path $src 'ModularAssistDevice.cpp'), [Text.Encoding]::GetEncoding(949))
$reqIds = @{}
foreach ($f in [regex]::Matches($cpp, '(?ms)^void CModularAssistDevice::(\w+)\(REQUEST_USB_DEVICE_DATA[^)]*\)\s*\{(.*?)^\}')) {
    $ids = [regex]::Matches($f.Groups[2].Value, 'nRequestID\s*==\s*(REQIDX_\w+)') | ForEach-Object { $_.Groups[1].Value } | Select-Object -Unique
    $reqIds[$f.Groups[1].Value] = @($ids)
}

# calls that end the session go last, in the original OnClose order
$last = @('A.SetExecuteStandbySEMPowerOffMode()', 'A.UsbDeviceDisconnect()', 'A.SetSemSystemShutDownExecute(int)')

function Arg([string]$t, [int]$i) {
    switch ($t) { 'double' { "$Value.5" } 'CString' { "$Value.25" } 'HWND' { '1' } 'char*' { "$Value;" } default { "$Value" } }
}
function Req([int]$id) {
    $n = (0..5 | ForEach-Object { $Value + $_ }) -join ','
    $d = (0..3 | ForEach-Object { "$($Value + $_).5" }) -join ','
    "$id,0,6;$n;$d;$Value"
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("# generated by make_assist.ps1 -Value $Value (do not edit)")
$startup | Where-Object { $_ -notmatch '^#' } | ForEach-Object { $lines.Add($_) }
function Emit([string]$k) {
    $name = $k.Substring(2, $k.IndexOf('(') - 2)
    $types = @($k.Substring($k.IndexOf('(') + 1).TrimEnd(')') -split ',' | Where-Object { $_ })
    if ($types -contains 'REQUEST_USB_DEVICE_DATA*') {
        $ids = @($reqIds[$name])
        if ($ids.Count -eq 0) { $ids = @('') }
        foreach ($id in $ids) {
            $num = $(if ($id) { $reqVal[$id] } else { 0 })
            $script:lines.Add("CALL $k " + (Req $num))
        }
        return
    }
    $script:lines.Add(("CALL $k " + (($types | ForEach-Object { Arg $_ 0 }) -join ' ')).TrimEnd())
}
foreach ($k in $keys) { if ($last -notcontains $k) { Emit $k } }
foreach ($k in $last) { if ($keys -contains $k) { Emit $k } }
$out = Join-Path $PSScriptRoot "scripts\$Name.txt"
[IO.File]::WriteAllLines($out, $lines, (New-Object Text.UTF8Encoding($false)))
"make_assist: $($lines.Count) lines -> $out"
