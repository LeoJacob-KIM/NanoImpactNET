# Generate scripts\rx.txt: every Spellman response code (the 35 in m_szFEPowerCommand + unknown ones) with many argument
# shapes (space positions decide how the original splits arguments), fed in chunks that cut messages at odd places.
# Each group of up to 8 messages ends with a chunk that ends in LF, so the main dialog line buffer never reaches 4096 bytes.
#   powershell -File make_rx.ps1
# Keep ASCII.
$codes = @('00', '01', '02', '03', '04', '05', '08', '09', '0A', '0B', '0E', '10', '11', '12', '13', '14', '15', '16', '17', '1A', '1C', '1D',
    '1E', '1F', '20', '21', '24', '26', '28', '29', '2A', '2B', '50', '52', '53', '77', '0G', '5')
$argsList = @(
    '', '0', '45', '45 3', '04 1', '00 0', '99 F', '12 \x01',
    '00000000', 'FFFFFFFF', '0000001F', '12345678', '9ABCDEF0', 'A5A5A5A5', '5A5A5A5A', 'zzzzzzzz', '00FF00FF', 'FF00FF00',
    '0 V0.01 03/06/15', '1 V1.23 31/12/22', '2 V9.99 01/01/00',
    '60 15000.0', 'E5 15000.0', 'E0 1.5', 'C3 123', 'A1 0.00', '36 30000.0', '45 1234.5', '43 99', '41 7', '4F 12345.6', '00 1234567', 'EE 12',
    '100 200', '1 2', '12345 54321', '1234 4321', '12 34567', '123 4567',
    '1234.56', '0012.34', '1.2', '123', '1234567',
    '15000.0 1234.5 123.4 1234.5 0000001F', '1.0 2.0 3.0 4.0 FFFFFFFF', '12345.6 1234567 1234 123456 12345678', '123 1234 12345 1234 A5A5A5A5',
    '12 34', '1 23', '  ', '1  2'
)
function Checksum([string]$body) {
    $sum = 0
    foreach ($c in $body.ToCharArray()) { $sum += [int]$c }
    $cs = ((0x200 - $sum) -band 0x7F) -bor 0x40
    return $cs.ToString('X2')
}
$messages = New-Object System.Collections.Generic.List[string]
foreach ($code in $codes) {
    foreach ($a in $argsList) {
        $body = $code + $a + ' '
        $messages.Add(':' + $body + (Checksum $body) + '\n')
    }
}
# odd lines: noise before ':', CR LF endings, line without ':', two colons, short command, embedded NUL
$extra = @('xx:0845 15000.0 4A\n', ':0845 15000.0 4A\r\n', 'garbage\n', '::0845 1.0 4A\n', ':0\n', ':\n', ':08\x0045 1.0 4A\n', ':02000000FF 4A\n:0145 3 4F\n')
$sizes = @(1, 7, 64, 3, 200, 13, 29, 2, 41)
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('# generated by make_rx.ps1 - every response code x argument shape, chunked')
$lines.Add('INIT')
$group = 0
function Emit-Group([string[]]$msgs) {
    # one stream; escapes count as one byte when cutting, so cut on the unescaped form and re-escape
    $raw = New-Object System.Collections.Generic.List[byte]
    foreach ($m in $msgs) {
        for ($i = 0; $i -lt $m.Length; $i++) {
            if ($m[$i] -eq '\' -and $i + 1 -lt $m.Length) {
                $n = $m[$i + 1]
                if ($n -eq 'n') { $raw.Add(10); $i++; continue }
                if ($n -eq 'r') { $raw.Add(13); $i++; continue }
                if ($n -eq 'x') { $raw.Add([Convert]::ToByte($m.Substring($i + 2, 2), 16)); $i += 3; continue }
            }
            $raw.Add([byte][char]$m[$i])
        }
    }
    $script:lines.Add('CHECK ' + ($script:group % 2))
    $script:lines.Add('OPEN ' + (3 + $script:group % 5))
    $pos = 0; $k = $script:group
    while ($pos -lt $raw.Count) {
        $n = [Math]::Min($sizes[$k % $sizes.Count], $raw.Count - $pos); $k++
        $sb = New-Object Text.StringBuilder
        for ($i = $pos; $i -lt $pos + $n; $i++) {
            $b = $raw[$i]
            if ($b -eq 10) { [void]$sb.Append('\n') } elseif ($b -eq 13) { [void]$sb.Append('\r') } elseif ($b -eq 92) { [void]$sb.Append('\\') }
            elseif ($b -lt 32 -or $b -gt 126) { [void]$sb.Append('\x' + $b.ToString('X2')) } else { [void]$sb.Append([char]$b) }
        }
        $script:lines.Add('RX ' + $sb.ToString())
        $pos += $n
    }
    $script:lines.Add('RUN')
    $script:group++
}
for ($i = 0; $i -lt $messages.Count; $i += 8) { Emit-Group ($messages.GetRange($i, [Math]::Min(8, $messages.Count - $i)).ToArray()) }
foreach ($e in $extra) { Emit-Group @($e, ':0145 3 4F\n') }
$out = Join-Path $PSScriptRoot 'scripts\rx.txt'
[IO.File]::WriteAllLines($out, $lines, (New-Object Text.UTF8Encoding($false)))
"make_rx: $($messages.Count) messages + $($extra.Count) odd lines, $group groups -> $out"
