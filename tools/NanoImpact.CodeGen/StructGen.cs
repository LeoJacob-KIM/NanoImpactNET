using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

namespace NanoImpact.CodeGen
{
    /// <summary>
    /// DefineStructCode.h의 화면 쪽 구조체(파일로 저장하지 않는 값 묶음) → C# 클래스.
    ///   NanoImpact.CodeGen structs &lt;DefineStructCode.h&gt; &lt;출력.cs&gt; &lt;fields 폴더&gt; 이름...
    /// 필드 이름은 원본 그대로, 배열은 원본 길이, char[N]은 CharBuffer(N). CopyFrom은 원본 memcpy(&amp;a, &amp;b, sizeof) 자리.
    /// fields 폴더에는 구조체마다 &lt;이름&gt;.fields.inc (FIELD(형식, 이름) / FIELDA(형식, 이름, 개수)) — 원본·C# 하네스가 같은 순서로 상태를 찍는다.
    /// </summary>
    internal static class StructGen
    {
        private sealed class Field
        {
            public string CType;
            public string Name;
            public string Count; // null = 배열 아님 (C# 식, 상수는 Def.)
            public string RawCount; // 원본 식 (C++ 하네스용)
            public string Comment;
        }

        private static readonly Dictionary<string, string> CsType = new Dictionary<string, string>
        {
            ["int"] = "int", ["BOOL"] = "int", ["INT"] = "int", ["long"] = "int", ["LONG"] = "int",
            ["UINT"] = "uint", ["DWORD"] = "uint", ["ULONG"] = "uint",
            ["WORD"] = "ushort", ["USHORT"] = "ushort", ["short"] = "short",
            ["BYTE"] = "byte", ["UCHAR"] = "byte",
            ["double"] = "double", ["float"] = "float",
            ["LPVOID"] = "object", ["COLORREF"] = "uint",
        };

        // 하네스 상태 출력 형식 글자: I int, U uint, W ushort, B byte, D double, S char 배열
        private static readonly Dictionary<string, char> FieldCode = new Dictionary<string, char>
        {
            ["int"] = 'I', ["short"] = 'I', ["uint"] = 'U', ["ushort"] = 'W', ["byte"] = 'B', ["double"] = 'D', ["float"] = 'D',
        };

        public static void Run(string header, string outCs, string fieldsDir, IEnumerable<string> names)
        {
            string text = File.ReadAllText(header, Encoding.GetEncoding(949)).Replace("\r\n", "\n");
            var sb = new StringBuilder();
            sb.Append("// Generated by NanoImpact.CodeGen structs from DefineStructCode.h. Do not edit.\r\n");
            sb.Append("#pragma warning disable IDE1006 // 원본 이름 그대로\r\n");
            sb.Append("namespace NanoImpact.Core.Native\r\n{\r\n");
            int made = 0;
            foreach (string name in names)
            {
                Match m = Regex.Match(text, @"typedef\s+struct\s+\w*\s*\{([^{}]*)\}\s*" + Regex.Escape(name) + @"\s*[,;]");
                if (!m.Success) throw new InvalidOperationException("구조체를 찾지 못함: " + name);
                int line = text.Substring(0, m.Index).Count(c => c == '\n') + 1;
                List<Field> fields = Parse(m.Groups[1].Value, name);

                sb.Append("    /// <summary>원본 ").Append(name).Append(" (DefineStructCode.h:").Append(line).Append(")</summary>\r\n");
                sb.Append("    public sealed class ").Append(name).Append("\r\n    {\r\n");
                foreach (Field f in fields)
                {
                    string c = f.Comment.Length > 0 ? " // " + f.Comment : "";
                    if (f.CType == "char")
                        sb.Append("        public readonly CharBuffer ").Append(f.Name).Append(" = new CharBuffer(").Append(f.Count ?? "1").Append(");").Append(c).Append("\r\n");
                    else if (f.Count != null)
                        sb.Append("        public ").Append(CsType[f.CType]).Append("[] ").Append(f.Name).Append(" = new ").Append(CsType[f.CType]).Append('[').Append(f.Count).Append("];").Append(c).Append("\r\n");
                    else
                        sb.Append("        public ").Append(CsType[f.CType]).Append(' ').Append(f.Name).Append(';').Append(c).Append("\r\n");
                }
                sb.Append("\r\n        /// <summary>원본 memcpy(this, o, sizeof) — 배열·문자열 내용까지 복사</summary>\r\n");
                sb.Append("        public void CopyFrom(").Append(name).Append(" o)\r\n        {\r\n");
                foreach (Field f in fields)
                {
                    if (f.CType == "char") sb.Append("            CRuntime.memcpy(").Append(f.Name).Append(", o.").Append(f.Name).Append(", ").Append(f.Name).Append(".Capacity);\r\n");
                    else if (f.Count != null) sb.Append("            System.Array.Copy(o.").Append(f.Name).Append(", ").Append(f.Name).Append(", ").Append(f.Name).Append(".Length);\r\n");
                    else sb.Append("            ").Append(f.Name).Append(" = o.").Append(f.Name).Append(";\r\n");
                }
                sb.Append("        }\r\n    }\r\n\r\n");

                if (fieldsDir != null)
                {
                    var inc = new StringBuilder("// Generated by NanoImpact.CodeGen structs: fields of " + name + " in declaration order. Do not edit.\r\n");
                    foreach (Field f in fields)
                    {
                        if (f.CType == "LPVOID") continue;
                        char code = f.CType == "char" ? 'S' : FieldCode[CsType[f.CType]];
                        if (f.Count != null && f.CType != "char") inc.Append("FIELDA(").Append(code).Append(", ").Append(f.Name).Append(", ").Append(f.RawCount).Append(")\r\n");
                        else inc.Append("FIELD(").Append(code).Append(", ").Append(f.Name).Append(")\r\n");
                    }
                    File.WriteAllText(Path.Combine(fieldsDir, name + ".fields.inc"), inc.ToString(), Encoding.ASCII);
                }
                made++;
            }
            sb.Append("}\r\n");
            File.WriteAllText(outCs, sb.ToString(), new UTF8Encoding(true));
            Console.WriteLine("structs: {0}개 → {1}", made, outCs);
        }

        private static List<Field> Parse(string body, string name)
        {
            var list = new List<Field>();
            foreach (string raw in body.Split('\n'))
            {
                string line = raw;
                string comment = "";
                int ci = line.IndexOf("//", StringComparison.Ordinal);
                if (ci >= 0) { comment = line.Substring(ci + 2).Trim(); line = line.Substring(0, ci); }
                line = Regex.Replace(line, @"/\*.*?\*/", "").Trim();
                if (line.Length == 0) continue;
                Match m = Regex.Match(line, @"^(unsigned\s+\w+|\w+)\s+(\w+)\s*(?:\[([^\]]+)\])?\s*;$");
                if (!m.Success) throw new InvalidOperationException(name + ": 필드를 읽지 못함: " + line);
                string t = Regex.Replace(m.Groups[1].Value, @"\s+", " ");
                if (t == "unsigned int") t = "UINT";
                else if (t == "unsigned char") t = "BYTE";
                else if (t == "unsigned short") t = "WORD";
                if (t != "char" && !CsType.ContainsKey(t)) throw new InvalidOperationException(name + ": 모르는 형식 " + t);
                string count = m.Groups[3].Success ? Regex.Replace(m.Groups[3].Value, @"\b([A-Z][A-Z0-9_]+)\b", "Def.$1").Replace(" ", "") : null;
                list.Add(new Field { CType = t, Name = m.Groups[2].Value, Count = count, RawCount = m.Groups[3].Success ? m.Groups[3].Value.Trim() : null, Comment = comment });
            }
            return list;
        }
    }
}
