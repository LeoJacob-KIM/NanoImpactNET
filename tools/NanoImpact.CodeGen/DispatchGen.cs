using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

namespace NanoImpact.CodeGen
{
    /// <summary>
    /// USB_FT232H_Device.h의 extern 선언 → device_harness\dispatch.inc (시험 스크립트에서 이름으로 원본 함수를 부르는 표).
    /// 키는 "AfxName(type,type)" — C# 쪽도 같은 키를 [Afx("...")] 특성으로 단다.
    /// </summary>
    internal static class DispatchGen
    {
        private static readonly Dictionary<string, string> ArgCode = new Dictionary<string, string>
        {
            ["int"] = "(int)a.Int({0})",
            ["INT"] = "(INT)a.Int({0})",
            ["UINT"] = "(UINT)a.Int({0})",
            ["BOOL"] = "(BOOL)a.Int({0})",
            ["WORD"] = "(WORD)a.Int({0})",
            ["DWORD"] = "(DWORD)a.Int({0})",
            ["BYTE"] = "(BYTE)a.Int({0})",
            ["UCHAR"] = "(UCHAR)a.Int({0})",
            ["ULONG"] = "(ULONG)a.Int({0})",
            ["USHORT"] = "(USHORT)a.Int({0})",
            ["double"] = "a.Dbl({0})",
            ["char*"] = "a.Str({0})",
            ["HWND"] = "(HWND)(INT_PTR)a.Int({0})",
        };

        private static readonly Dictionary<string, string> RetMacro = new Dictionary<string, string>
        {
            ["int"] = "RI", ["INT"] = "RI", ["UINT"] = "RI", ["BOOL"] = "RI", ["DWORD"] = "RI", ["WORD"] = "RI",
            ["ULONG"] = "RI", ["FT_STATUS"] = "RI", ["double"] = "RD", ["void"] = "RV",
        };

        public static void Run(string header, string outPath)
        {
            string text = Regex.Replace(File.ReadAllText(header, System.Text.Encoding.GetEncoding(949)), @"/\*.*?\*/", "", RegexOptions.Singleline);
            var rx = new Regex(@"^\s*extern\s+([A-Za-z_]\w*\s*\**)\s+(Afx\w+)\s*\(([^)]*)\)\s*;");
            var keys = new HashSet<string>();
            var sb = new StringBuilder("// Generated by NanoImpact.CodeGen dispatch from USB_FT232H_Device.h. Do not edit.\r\n");
            int made = 0;
            var skipped = new List<string>();
            foreach (string raw in text.Split('\n'))
            {
                string line = Regex.Replace(raw, @"//.*$", "");
                Match m = rx.Match(line);
                if (!m.Success) continue;
                string ret = m.Groups[1].Value.Replace(" ", "");
                string name = m.Groups[2].Value;
                var types = new List<string>();
                bool ok = RetMacro.ContainsKey(ret);
                foreach (string p0 in m.Groups[3].Value.Split(','))
                {
                    string p = Regex.Replace(p0, @"=.*$", "").Trim();
                    if (p.Length == 0 || p == "void") continue;
                    string type;
                    Match pm = Regex.Match(p, @"^(.*?[\s\*])\s*([A-Za-z_]\w*)$");
                    type = pm.Success && pm.Groups[1].Value.Trim().Length > 0 ? pm.Groups[1].Value : p;
                    type = Regex.Replace(type, @"\s+", "");
                    if (!ArgCode.ContainsKey(type)) ok = false;
                    types.Add(type);
                }
                string key = name + "(" + string.Join(",", types) + ")";
                if (!ok) { skipped.Add(ret + " " + key); continue; }
                if (!keys.Add(key)) continue;

                string call = name + "(" + string.Join(", ", types.Select((t, i) => string.Format(ArgCode[t], i))) + ")";
                sb.Append("DISPATCH(\"").Append(key).Append("\", ").Append(types.Count).Append(", ").Append(RetMacro[ret]).Append('(').Append(call).Append("))\r\n");
                made++;
            }
            File.WriteAllText(outPath, sb.ToString(), Encoding.ASCII);
            Console.WriteLine("dispatch: {0}개 생성, {1}개 제외 (포인터·구조체 인자/반환)", made, skipped.Count);
            foreach (string s in skipped) Console.WriteLine("  제외 " + s);
        }

        /// <summary>클래스 헤더 모드에서 더 받는 인자 형식 (CString, 요청 구조체 포인터)</summary>
        private static readonly Dictionary<string, string> ClassArgCode = new Dictionary<string, string>
        {
            ["CString"] = "a.CStr({0})",
            ["REQUEST_USB_DEVICE_DATA*"] = "a.Req({0})",
        };

        /// <summary>
        /// 클래스 헤더(ModularAssistDevice.h 등)의 public 메서드 선언 → 호출 표. 키는 "접두.Name(type,type)", 호출은 "객체.Name(...)".
        ///   NanoImpact.CodeGen dispatch-class &lt;헤더&gt; &lt;출력.inc&gt; &lt;접두&gt; &lt;객체 식&gt;
        /// 객체 포인터를 받는 설정 함수(SetOwnerWindow 등)는 하네스가 직접 연결하므로 빠진다.
        /// </summary>
        public static void RunClass(string header, string outPath, string prefix, string obj)
        {
            string text = Regex.Replace(File.ReadAllText(header, Encoding.GetEncoding(949)), @"/\*.*?\*/", "", RegexOptions.Singleline);
            var rx = new Regex(@"^\s*(void|int|double|BOOL|UINT|DWORD)\s+([A-Za-z_]\w*)\s*\(([^)]*)\)\s*;");
            var keys = new HashSet<string>();
            var sb = new StringBuilder("// Generated by NanoImpact.CodeGen dispatch-class from " + Path.GetFileName(header) + ". Do not edit.\r\n");
            int made = 0;
            var skipped = new List<string>();
            foreach (string raw in text.Split('\n'))
            {
                string line = Regex.Replace(raw, @"//.*$", "");
                line = Regex.Replace(line, @"_T\s*\(\s*""[^""]*""\s*\)", "0"); // 기본값 _T("") 안의 괄호
                Match m = rx.Match(line);
                if (!m.Success) continue;
                string ret = m.Groups[1].Value;
                string name = m.Groups[2].Value;
                var types = new List<string>();
                bool ok = true;
                foreach (string p0 in m.Groups[3].Value.Split(','))
                {
                    string p = Regex.Replace(p0, @"=.*$", "").Trim();
                    if (p.Length == 0 || p == "void") continue;
                    Match pm = Regex.Match(p, @"^(.*?[\s\*])\s*([A-Za-z_]\w*)$");
                    string type = Regex.Replace(pm.Success && pm.Groups[1].Value.Trim().Length > 0 ? pm.Groups[1].Value : p, @"\s+", "");
                    if (!ArgCode.ContainsKey(type) && !ClassArgCode.ContainsKey(type)) ok = false;
                    types.Add(type);
                }
                string key = prefix + "." + name + "(" + string.Join(",", types) + ")";
                if (!ok) { skipped.Add(ret + " " + key); continue; }
                if (!keys.Add(key)) continue;
                string call = obj + "." + name + "(" + string.Join(", ", types.Select((t, i) => string.Format(ArgCode.TryGetValue(t, out string c) ? c : ClassArgCode[t], i))) + ")";
                sb.Append("DISPATCH(\"").Append(key).Append("\", ").Append(types.Count).Append(", ").Append(RetMacro[ret]).Append('(').Append(call).Append("))\r\n");
                made++;
            }
            File.WriteAllText(outPath, sb.ToString(), Encoding.ASCII);
            Console.WriteLine("dispatch-class: {0}개 생성, {1}개 제외", made, skipped.Count);
            foreach (string s in skipped) Console.WriteLine("  제외 " + s);
        }
    }
}
